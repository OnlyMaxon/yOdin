#!/usr/bin/env node
/**
 * Regenerates functions/src/pushStrings.ts from src/locales.
 *
 * A push has to arrive with its text already written: Android will not render
 * anything for a data-only message once the app is killed, so the body cannot
 * be composed on the device the way the in-app list composes it. That means
 * the server needs the same strings the app has, in whatever language the
 * recipient reads — which is why `language` is mirrored onto the profile.
 *
 * Only the handful of keys a notification can use are copied, so this stays a
 * few kilobytes rather than a second copy of every translation.
 *
 *     node scripts/generate-push-strings.js
 */
const fs = require('fs');
const path = require('path');

// Notification type → key under `notifications` in the locale files.
const KEYS = {
  reply: 'replied',
  accepted: 'accepted',
  participant: 'joinedEvent',
  event: 'postedEvent',
  mention: 'mentioned',
  removed: 'contentRemoved',
  blocked: 'blocked',
};

const root = path.join(__dirname, '..');
const localeDir = path.join(root, 'src', 'locales');
const locales = fs
  .readdirSync(localeDir)
  .filter((d) => fs.statSync(path.join(localeDir, d)).isDirectory())
  .sort();

const tables = {};
const problems = [];

for (const locale of locales) {
  const json = JSON.parse(
    fs.readFileSync(path.join(localeDir, locale, 'translation.json'), 'utf8'),
  );
  const notifications = json.notifications ?? {};
  const table = {};
  for (const [type, key] of Object.entries(KEYS)) {
    const value = notifications[key];
    if (typeof value !== 'string' || value.length === 0) {
      problems.push(`${locale}: notifications.${key}`);
      continue;
    }
    table[type] = value;
  }
  tables[locale] = table;
}

if (problems.length > 0) {
  // A missing string would mean a push with an empty body, which is worse than
  // a build that stops and says which one.
  throw new Error(`missing push strings:\n  ${problems.join('\n  ')}`);
}

const body = Object.entries(tables)
  .map(([locale, table]) => {
    const rows = Object.entries(table)
      .map(([type, text]) => `    ${type}: ${JSON.stringify(text)},`)
      .join('\n');
    return `  ${locale}: {\n${rows}\n  },`;
  })
  .join('\n');

const out = `// Generated by scripts/generate-push-strings.js — do not edit by hand.
//
// The body text of a push, per language and notification type. The in-app list
// renders these through i18next on the device; a push cannot, because Android
// shows nothing for a data-only message once the app is killed, so the text has
// to be written server-side before it is sent.
//
// Keyed by language, then by notification type. Falls back to 'en' for a
// language with no table — see pushBody() in push.ts.
export const PUSH_STRINGS: Record<string, Record<string, string>> = {
${body}
};
`;

fs.writeFileSync(path.join(root, 'functions', 'src', 'pushStrings.ts'), out, 'utf8');
console.log(
  `pushStrings.ts: ${locales.length} locales × ${Object.keys(KEYS).length} types`,
);
